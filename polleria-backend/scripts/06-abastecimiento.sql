WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE TABLE POLLERIA.INSUMOS (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 NOMBRE VARCHAR2(100 CHAR) NOT NULL,
 DESCRIPCION VARCHAR2(500 CHAR),
 UNIDAD_MEDIDA VARCHAR2(10 CHAR) NOT NULL,
 STOCK_ACTUAL NUMBER(19,3) DEFAULT 0 NOT NULL,
 ACTIVO NUMBER(1,0) DEFAULT 1 NOT NULL,
 CONSTRAINT PK_INSUMOS PRIMARY KEY(ID),
 CONSTRAINT CK_INSUMOS_NOMBRE CHECK(REGEXP_LIKE(NOMBRE,'[^[:space:]]')),
 CONSTRAINT CK_INSUMOS_UNIDAD CHECK(UNIDAD_MEDIDA IN('UNIDAD','KG','G','L','ML')),
 CONSTRAINT CK_INSUMOS_STOCK CHECK(STOCK_ACTUAL>=0),
 CONSTRAINT CK_INSUMOS_ACTIVO CHECK(ACTIVO IN(0,1))
);
CREATE TABLE POLLERIA.PROVEEDORES (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 RAZON_SOCIAL VARCHAR2(150 CHAR) NOT NULL,
 RUC VARCHAR2(11 CHAR),
 TELEFONO VARCHAR2(12 CHAR),
 CORREO VARCHAR2(254 CHAR),
 DIRECCION VARCHAR2(300 CHAR),
 ACTIVO NUMBER(1,0) DEFAULT 1 NOT NULL,
 CONSTRAINT PK_PROVEEDORES PRIMARY KEY(ID),
 CONSTRAINT UK_PROVEEDORES_RUC UNIQUE(RUC),
 CONSTRAINT CK_PROVEEDORES_RAZON CHECK(REGEXP_LIKE(RAZON_SOCIAL,'[^[:space:]]')),
 CONSTRAINT CK_PROVEEDORES_RUC CHECK(RUC IS NULL OR REGEXP_LIKE(RUC,'^[0-9]{11}$')),
 CONSTRAINT CK_PROVEEDORES_TELEFONO CHECK(TELEFONO IS NULL OR REGEXP_LIKE(TELEFONO,'^(\+51)?[0-9]{7,9}$')),
 CONSTRAINT CK_PROVEEDORES_ACTIVO CHECK(ACTIVO IN(0,1))
);
CREATE TABLE POLLERIA.COMPRAS (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 PROVEEDOR_ID NUMBER(19,0) NOT NULL,
 FECHA TIMESTAMP NOT NULL,
 TOTAL NUMBER(19,2) NOT NULL,
 CONSTRAINT PK_COMPRAS PRIMARY KEY(ID),
 CONSTRAINT FK_COMPRAS_PROVEEDOR FOREIGN KEY(PROVEEDOR_ID) REFERENCES POLLERIA.PROVEEDORES(ID),
 CONSTRAINT CK_COMPRAS_TOTAL CHECK(TOTAL>=0)
);
CREATE TABLE POLLERIA.DETALLE_COMPRAS (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 COMPRA_ID NUMBER(19,0) NOT NULL,
 INSUMO_ID NUMBER(19,0) NOT NULL,
 NOMBRE_INSUMO VARCHAR2(100 CHAR) NOT NULL,
 UNIDAD_MEDIDA VARCHAR2(10 CHAR) NOT NULL,
 CANTIDAD NUMBER(19,3) NOT NULL,
 COSTO_UNITARIO NUMBER(19,4) NOT NULL,
 SUBTOTAL NUMBER(19,2) NOT NULL,
 CONSTRAINT PK_DETALLE_COMPRAS PRIMARY KEY(ID),
 CONSTRAINT FK_DETCOMPRA_COMPRA FOREIGN KEY(COMPRA_ID) REFERENCES POLLERIA.COMPRAS(ID),
 CONSTRAINT FK_DETCOMPRA_INSUMO FOREIGN KEY(INSUMO_ID) REFERENCES POLLERIA.INSUMOS(ID),
 CONSTRAINT UK_DETCOMPRA_INSUMO UNIQUE(COMPRA_ID,INSUMO_ID),
 CONSTRAINT CK_DETCOMPRA_CANTIDAD CHECK(CANTIDAD>0),
 CONSTRAINT CK_DETCOMPRA_COSTO CHECK(COSTO_UNITARIO>0),
 CONSTRAINT CK_DETCOMPRA_SUBTOTAL CHECK(SUBTOTAL>=0 AND SUBTOTAL=ROUND(CANTIDAD*COSTO_UNITARIO,2)),
 CONSTRAINT CK_DETCOMPRA_UNIDAD CHECK(UNIDAD_MEDIDA IN('UNIDAD','KG','G','L','ML'))
);
CREATE TABLE POLLERIA.MOVIMIENTOS_INVENTARIO (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 INSUMO_ID NUMBER(19,0) NOT NULL,
 TIPO VARCHAR2(10 CHAR) NOT NULL,
 CANTIDAD NUMBER(19,3) NOT NULL,
 STOCK_ANTERIOR NUMBER(19,3) NOT NULL,
 STOCK_POSTERIOR NUMBER(19,3) NOT NULL,
 FECHA TIMESTAMP NOT NULL,
 MOTIVO VARCHAR2(500 CHAR) NOT NULL,
 COMPRA_ID NUMBER(19,0),
 CONSTRAINT PK_MOVIMIENTOS_INVENTARIO PRIMARY KEY(ID),
 CONSTRAINT FK_MOVINV_INSUMO FOREIGN KEY(INSUMO_ID) REFERENCES POLLERIA.INSUMOS(ID),
 CONSTRAINT FK_MOVINV_COMPRA FOREIGN KEY(COMPRA_ID) REFERENCES POLLERIA.COMPRAS(ID),
 CONSTRAINT CK_MOVINV_TIPO CHECK(TIPO IN('ENTRADA','SALIDA','AJUSTE')),
 CONSTRAINT CK_MOVINV_STOCK CHECK(STOCK_ANTERIOR>=0 AND STOCK_POSTERIOR>=0),
 CONSTRAINT CK_MOVINV_MOTIVO CHECK(REGEXP_LIKE(MOTIVO,'[^[:space:]]')),
 CONSTRAINT CK_MOVINV_CALCULO CHECK(
  (TIPO='ENTRADA' AND CANTIDAD>0 AND COMPRA_ID IS NOT NULL AND STOCK_POSTERIOR=STOCK_ANTERIOR+CANTIDAD) OR
  (TIPO='SALIDA' AND CANTIDAD>0 AND COMPRA_ID IS NULL AND STOCK_POSTERIOR=STOCK_ANTERIOR-CANTIDAD) OR
  (TIPO='AJUSTE' AND CANTIDAD<>0 AND COMPRA_ID IS NULL AND STOCK_POSTERIOR=STOCK_ANTERIOR+CANTIDAD))
);
CREATE INDEX POLLERIA.IX_MOVINV_INSUMO_FECHA ON POLLERIA.MOVIMIENTOS_INVENTARIO(INSUMO_ID,FECHA);
CREATE INDEX POLLERIA.IX_COMPRAS_PROVEEDOR_FECHA ON POLLERIA.COMPRAS(PROVEEDOR_ID,FECHA);
