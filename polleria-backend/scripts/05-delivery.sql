CREATE TABLE POLLERIA.REPARTIDORES (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 KEYCLOAK_SUB VARCHAR2(255 CHAR) NOT NULL,
 NOMBRE_VISIBLE VARCHAR2(200 CHAR) NOT NULL,
 ACTIVO NUMBER(1,0) DEFAULT 1 NOT NULL,
 CONSTRAINT PK_REPARTIDORES PRIMARY KEY (ID),
 CONSTRAINT UK_REPARTIDORES_SUB UNIQUE (KEYCLOAK_SUB),
 CONSTRAINT CK_REPARTIDORES_ACTIVO CHECK (ACTIVO IN (0,1)),
 CONSTRAINT CK_REPARTIDORES_NOMBRE CHECK (REGEXP_LIKE(NOMBRE_VISIBLE,'[^[:space:]]')),
 CONSTRAINT CK_REPARTIDORES_SUB CHECK (REGEXP_LIKE(KEYCLOAK_SUB,'[^[:space:]]'))
);
CREATE TABLE POLLERIA.ENTREGAS (
 ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
 PEDIDO_ID NUMBER(19,0) NOT NULL,
 REPARTIDOR_ID NUMBER(19,0) NOT NULL,
 FECHA_ASIGNACION TIMESTAMP NOT NULL,
 FECHA_SALIDA TIMESTAMP,
 FECHA_ENTREGA TIMESTAMP,
 ESTADO VARCHAR2(20 CHAR) NOT NULL,
 OBSERVACION VARCHAR2(2000 CHAR),
 CONSTRAINT PK_ENTREGAS PRIMARY KEY (ID),
 CONSTRAINT UK_ENTREGAS_PEDIDO UNIQUE (PEDIDO_ID),
 CONSTRAINT FK_ENTREGAS_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES POLLERIA.PEDIDOS(ID),
 CONSTRAINT FK_ENTREGAS_REPARTIDOR FOREIGN KEY (REPARTIDOR_ID) REFERENCES POLLERIA.REPARTIDORES(ID),
 CONSTRAINT CK_ENTREGAS_ESTADO CHECK (ESTADO IN ('ASIGNADO','EN_CAMINO','ENTREGADO','NO_ENTREGADO')),
 CONSTRAINT CK_ENTREGAS_FECHAS CHECK (
  (ESTADO='ASIGNADO' AND FECHA_SALIDA IS NULL AND FECHA_ENTREGA IS NULL) OR
  (ESTADO IN ('EN_CAMINO','NO_ENTREGADO') AND FECHA_SALIDA IS NOT NULL AND FECHA_ENTREGA IS NULL) OR
  (ESTADO='ENTREGADO' AND FECHA_SALIDA IS NOT NULL AND FECHA_ENTREGA IS NOT NULL)),
 CONSTRAINT CK_ENTREGAS_ORDEN_FECHAS CHECK ((FECHA_SALIDA IS NULL OR FECHA_SALIDA>=FECHA_ASIGNACION) AND (FECHA_ENTREGA IS NULL OR FECHA_ENTREGA>=FECHA_SALIDA)),
 CONSTRAINT CK_ENTREGAS_OBSERVACION CHECK (ESTADO<>'NO_ENTREGADO' OR (OBSERVACION IS NOT NULL AND REGEXP_LIKE(OBSERVACION,'[^[:space:]]')))
);
CREATE INDEX POLLERIA.IX_ENTREGAS_REPARTIDOR ON POLLERIA.ENTREGAS(REPARTIDOR_ID);
