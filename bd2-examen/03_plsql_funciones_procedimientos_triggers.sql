-- P1. Registrar la cabecera de un pedido (parámetro OUT con el ID creado)
CREATE OR REPLACE PROCEDURE REGISTRAR_PEDIDO (
  P_ID_CLIENTE  IN  NUMBER,
  P_TIPO_PEDIDO IN  VARCHAR2,
  P_METODO_PAGO IN  VARCHAR2,
  P_ID_PEDIDO   OUT NUMBER,
  P_ID_MESA     IN  NUMBER   DEFAULT NULL,
  P_DIRECCION   IN  VARCHAR2 DEFAULT NULL,
  P_FECHA       IN  DATE     DEFAULT SYSDATE
)
AS
  V_ESTADO_MESA MESAS.ESTADO%TYPE;
BEGIN
  IF P_TIPO_PEDIDO = 'MESA' THEN
    SELECT ESTADO INTO V_ESTADO_MESA
    FROM MESAS
    WHERE ID_MESA = P_ID_MESA
    FOR UPDATE;

    IF V_ESTADO_MESA <> 'DISPONIBLE' THEN
      RAISE_APPLICATION_ERROR(-20003, 'La mesa ' || P_ID_MESA || ' no está disponible (' || V_ESTADO_MESA || ')');
    END IF;
  END IF;

  INSERT INTO PEDIDOS (ID_CLIENTE, ID_MESA, FECHA_PEDIDO, TIPO_PEDIDO, METODO_PAGO, DIRECCION_ENTREGA)
  VALUES (P_ID_CLIENTE, P_ID_MESA, P_FECHA, P_TIPO_PEDIDO, P_METODO_PAGO, P_DIRECCION)
  RETURNING ID_PEDIDO INTO P_ID_PEDIDO;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20004, 'La mesa ' || NVL(TO_CHAR(P_ID_MESA), '(vacía)') || ' no existe');
END;
/

-- P2. Agregar un producto a un pedido PENDIENTE y recalcular base, IGV (18 %) y total.
--     El trigger TRG_DETALLE_STOCK valida y descuenta el stock.
CREATE OR REPLACE PROCEDURE AGREGAR_PRODUCTO_PEDIDO (
  P_ID_PEDIDO   IN NUMBER,
  P_ID_PRODUCTO IN NUMBER,
  P_CANTIDAD    IN NUMBER
)
AS
  V_ESTADO PEDIDOS.ESTADO%TYPE;
  V_TOTAL  PEDIDOS.TOTAL%TYPE;
  V_BASE   PEDIDOS.BASE_IMPONIBLE%TYPE;
BEGIN
  SELECT ESTADO INTO V_ESTADO
  FROM PEDIDOS
  WHERE ID_PEDIDO = P_ID_PEDIDO
  FOR UPDATE;

  IF V_ESTADO <> 'PENDIENTE' THEN
    RAISE_APPLICATION_ERROR(-20005, 'Solo se agregan productos a pedidos PENDIENTES (el pedido '
                                    || P_ID_PEDIDO || ' está ' || V_ESTADO || ')');
  END IF;

  INSERT INTO DETALLE_PEDIDOS (ID_PEDIDO, ID_PRODUCTO, CANTIDAD, PRECIO_UNITARIO, SUBTOTAL)
  VALUES (P_ID_PEDIDO, P_ID_PRODUCTO, P_CANTIDAD, OBTENER_PRECIO_PRODUCTO(P_ID_PRODUCTO), 0);

  SELECT SUM(SUBTOTAL) INTO V_TOTAL
  FROM DETALLE_PEDIDOS
  WHERE ID_PEDIDO = P_ID_PEDIDO;

  -- Los precios ya incluyen IGV: base = total / 1.18
  V_BASE := ROUND(V_TOTAL / 1.18, 2);

  UPDATE PEDIDOS
  SET TOTAL = V_TOTAL,
      BASE_IMPONIBLE = V_BASE,
      IGV = V_TOTAL - V_BASE
  WHERE ID_PEDIDO = P_ID_PEDIDO;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20006, 'El pedido ' || P_ID_PEDIDO || ' no existe');
END;
/

-- P3. Procesar el cobro (equivale a PROCESAR_VENTA): registra el pago,
--     marca el pedido como ENTREGADO, libera la mesa y confirma con COMMIT.
CREATE OR REPLACE PROCEDURE REGISTRAR_PAGO (
  P_ID_PEDIDO      IN NUMBER,
  P_MONTO_RECIBIDO IN NUMBER
)
AS
  V_PEDIDO PEDIDOS%ROWTYPE;
BEGIN
  SELECT * INTO V_PEDIDO
  FROM PEDIDOS
  WHERE ID_PEDIDO = P_ID_PEDIDO
  FOR UPDATE;

  IF V_PEDIDO.ESTADO IN ('ENTREGADO', 'CANCELADO') THEN
    RAISE_APPLICATION_ERROR(-20008, 'El pedido ' || P_ID_PEDIDO || ' ya está ' || V_PEDIDO.ESTADO);
  END IF;

  IF V_PEDIDO.TOTAL = 0 THEN
    RAISE_APPLICATION_ERROR(-20009, 'El pedido ' || P_ID_PEDIDO || ' no tiene productos');
  END IF;

  IF P_MONTO_RECIBIDO < V_PEDIDO.TOTAL THEN
    RAISE_APPLICATION_ERROR(-20010, 'Monto insuficiente: total S/ ' || V_PEDIDO.TOTAL
                                    || ', recibido S/ ' || P_MONTO_RECIBIDO);
  END IF;

  INSERT INTO PAGOS (ID_PEDIDO, METODO_PAGO, MONTO, MONTO_RECIBIDO, VUELTO, FECHA_PAGO)
  VALUES (P_ID_PEDIDO, V_PEDIDO.METODO_PAGO, V_PEDIDO.TOTAL, P_MONTO_RECIBIDO,
          P_MONTO_RECIBIDO - V_PEDIDO.TOTAL,
          -- Pedidos simulados de días anteriores: se cobran 1 hora después del pedido.
          CASE WHEN V_PEDIDO.FECHA_PEDIDO < TRUNC(SYSDATE)
               THEN V_PEDIDO.FECHA_PEDIDO + 1/24 ELSE SYSDATE END);

  UPDATE PEDIDOS SET ESTADO = 'ENTREGADO' WHERE ID_PEDIDO = P_ID_PEDIDO;

  IF V_PEDIDO.TIPO_PEDIDO = 'MESA' THEN
    UPDATE MESAS SET ESTADO = 'DISPONIBLE' WHERE ID_MESA = V_PEDIDO.ID_MESA;
  END IF;

  COMMIT;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20006, 'El pedido ' || P_ID_PEDIDO || ' no existe');
END;
/

-- P4. Reporte de ventas de un día con CURSOR y DBMS_OUTPUT
CREATE OR REPLACE PROCEDURE REPORTE_VENTAS_DIA (P_FECHA IN DATE DEFAULT SYSDATE)
AS
  CURSOR C_PEDIDOS IS
    SELECT PE.ID_PEDIDO,
           OBTENER_NOMBRE_CLIENTE(PE.ID_CLIENTE) AS CLIENTE,
           PE.TIPO_PEDIDO, PE.METODO_PAGO, PE.TOTAL
    FROM PEDIDOS PE
    WHERE PE.ESTADO = 'ENTREGADO'
      AND PE.FECHA_PEDIDO >= TRUNC(P_FECHA)
      AND PE.FECHA_PEDIDO <  TRUNC(P_FECHA) + 1
    ORDER BY PE.ID_PEDIDO;
  V_CANTIDAD NUMBER := 0;
BEGIN
  DBMS_OUTPUT.PUT_LINE('VENTAS DEL ' || TO_CHAR(P_FECHA, 'DD/MM/YYYY'));
  DBMS_OUTPUT.PUT_LINE(RPAD('PEDIDO', 8) || RPAD('CLIENTE', 28) || RPAD('TIPO', 13) || RPAD('PAGO', 10) || 'TOTAL');
  FOR R IN C_PEDIDOS LOOP
    V_CANTIDAD := V_CANTIDAD + 1;
    DBMS_OUTPUT.PUT_LINE(RPAD(R.ID_PEDIDO, 8) || RPAD(R.CLIENTE, 28) || RPAD(R.TIPO_PEDIDO, 13)
                         || RPAD(R.METODO_PAGO, 10) || TO_CHAR(R.TOTAL, '9990.00'));
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('Pedidos: ' || V_CANTIDAD || '   Total del día: S/ '
                       || TRIM(TO_CHAR(TOTAL_VENTAS_DIA(P_FECHA), '99990.00')));
END;
/

