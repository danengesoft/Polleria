-- ---------------------------------------------------------------------

-- T1. Antes de insertar un detalle: valida disponibilidad y stock,
--     descuenta el stock y calcula el subtotal.
CREATE OR REPLACE TRIGGER TRG_DETALLE_STOCK
BEFORE INSERT ON DETALLE_PEDIDOS
FOR EACH ROW
DECLARE
  V_STOCK      PRODUCTOS.STOCK%TYPE;
  V_DISPONIBLE PRODUCTOS.DISPONIBLE%TYPE;
BEGIN
  SELECT STOCK, DISPONIBLE INTO V_STOCK, V_DISPONIBLE
  FROM PRODUCTOS
  WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
  FOR UPDATE;

  IF V_DISPONIBLE = 0 THEN
    RAISE_APPLICATION_ERROR(-20007, 'El producto ' || :NEW.ID_PRODUCTO || ' no está disponible');
  END IF;

  IF V_STOCK < :NEW.CANTIDAD THEN
    RAISE_APPLICATION_ERROR(-20002, 'Stock insuficiente para el producto ' || :NEW.ID_PRODUCTO
                                    || ': hay ' || V_STOCK || ', se piden ' || :NEW.CANTIDAD);
  END IF;

  UPDATE PRODUCTOS
  SET STOCK = STOCK - :NEW.CANTIDAD
  WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

  :NEW.SUBTOTAL := :NEW.PRECIO_UNITARIO * :NEW.CANTIDAD;
END;
/

-- T2. Después de insertar un pedido de MESA: la mesa pasa a OCUPADA.
CREATE OR REPLACE TRIGGER TRG_PEDIDOS_OCUPAR_MESA
AFTER INSERT ON PEDIDOS
FOR EACH ROW
WHEN (NEW.TIPO_PEDIDO = 'MESA')
BEGIN
  UPDATE MESAS SET ESTADO = 'OCUPADA' WHERE ID_MESA = :NEW.ID_MESA;
END;
/

-- T3. Control antes de ELIMINAR o CANCELAR un pedido (usa :OLD y :NEW)
--   - Prohíbe DELETE: los pedidos se cancelan, no se borran.
--   - Un pedido ENTREGADO o CANCELADO ya no cambia de estado.
--   - Al cancelar: devuelve el stock y libera la mesa.
--   - Todo cambio de estado queda en AUDITORIA_PEDIDOS.
CREATE OR REPLACE TRIGGER TRG_PEDIDOS_CONTROL
BEFORE DELETE OR UPDATE OF ESTADO ON PEDIDOS
FOR EACH ROW
BEGIN
  IF DELETING THEN
    RAISE_APPLICATION_ERROR(-20011, 'Los pedidos no se eliminan. Cambie el pedido '
                                    || :OLD.ID_PEDIDO || ' a estado CANCELADO');
  END IF;

  IF :NEW.ESTADO <> :OLD.ESTADO THEN
    IF :OLD.ESTADO IN ('ENTREGADO', 'CANCELADO') THEN
      RAISE_APPLICATION_ERROR(-20012, 'El pedido ' || :OLD.ID_PEDIDO || ' ya está '
                                      || :OLD.ESTADO || ' y no puede cambiar de estado');
    END IF;

    IF :NEW.ESTADO = 'CANCELADO' THEN
      UPDATE PRODUCTOS P
      SET STOCK = STOCK + (SELECT SUM(D.CANTIDAD)
                           FROM DETALLE_PEDIDOS D
                           WHERE D.ID_PEDIDO = :OLD.ID_PEDIDO
                             AND D.ID_PRODUCTO = P.ID_PRODUCTO)
      WHERE P.ID_PRODUCTO IN (SELECT ID_PRODUCTO FROM DETALLE_PEDIDOS WHERE ID_PEDIDO = :OLD.ID_PEDIDO);

      IF :OLD.TIPO_PEDIDO = 'MESA' THEN
        UPDATE MESAS SET ESTADO = 'DISPONIBLE' WHERE ID_MESA = :OLD.ID_MESA;
      END IF;
    END IF;

    INSERT INTO AUDITORIA_PEDIDOS (ID_PEDIDO, ACCION, ESTADO_ANTERIOR, ESTADO_NUEVO, USUARIO_BD, FECHA)
    VALUES (:OLD.ID_PEDIDO, 'CAMBIO_ESTADO', :OLD.ESTADO, :NEW.ESTADO, USER, SYSDATE);
  END IF;
END;
/

