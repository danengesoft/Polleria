-- F1. Precio de un producto (NO_DATA_FOUND -> error personalizado)
CREATE OR REPLACE FUNCTION OBTENER_PRECIO_PRODUCTO (P_ID_PRODUCTO IN NUMBER)
RETURN NUMBER
AS
  V_PRECIO PRODUCTOS.PRECIO%TYPE;
BEGIN
  SELECT PRECIO INTO V_PRECIO
  FROM PRODUCTOS
  WHERE ID_PRODUCTO = P_ID_PRODUCTO;
  RETURN V_PRECIO;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'El producto ' || P_ID_PRODUCTO || ' no existe');
END;
/

-- F2. Stock de un producto
CREATE OR REPLACE FUNCTION OBTENER_STOCK_PRODUCTO (P_ID_PRODUCTO IN NUMBER)
RETURN NUMBER
AS
  V_STOCK PRODUCTOS.STOCK%TYPE;
BEGIN
  SELECT STOCK INTO V_STOCK
  FROM PRODUCTOS
  WHERE ID_PRODUCTO = P_ID_PRODUCTO;
  RETURN V_STOCK;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20001, 'El producto ' || P_ID_PRODUCTO || ' no existe');
END;
/

-- F3. Producto más vendido (por unidades, sin contar pedidos cancelados)
CREATE OR REPLACE FUNCTION PRODUCTO_MAS_VENDIDO
RETURN VARCHAR2
AS
  V_NOMBRE   PRODUCTOS.NOMBRE%TYPE;
  V_UNIDADES NUMBER;
BEGIN
  SELECT NOMBRE, UNIDADES INTO V_NOMBRE, V_UNIDADES
  FROM (
    SELECT P.NOMBRE, SUM(D.CANTIDAD) AS UNIDADES
    FROM DETALLE_PEDIDOS D
    JOIN PRODUCTOS P ON P.ID_PRODUCTO = D.ID_PRODUCTO
    JOIN PEDIDOS  PE ON PE.ID_PEDIDO  = D.ID_PEDIDO
    WHERE PE.ESTADO <> 'CANCELADO'
    GROUP BY P.NOMBRE
    ORDER BY UNIDADES DESC
  )
  WHERE ROWNUM = 1;
  RETURN V_NOMBRE || ' (' || V_UNIDADES || ' unidades)';
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN 'Sin ventas registradas';
END;
/

-- F4. Nombre completo del cliente
CREATE OR REPLACE FUNCTION OBTENER_NOMBRE_CLIENTE (P_ID_CLIENTE IN NUMBER)
RETURN VARCHAR2
AS
  V_NOMBRE VARCHAR2(201);
BEGIN
  SELECT NOMBRES || ' ' || APELLIDOS INTO V_NOMBRE
  FROM CLIENTES
  WHERE ID_CLIENTE = P_ID_CLIENTE;
  RETURN V_NOMBRE;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN 'Cliente no encontrado';
END;
/

-- F5. Total vendido (pedidos ENTREGADOS) en un día
CREATE OR REPLACE FUNCTION TOTAL_VENTAS_DIA (P_FECHA IN DATE)
RETURN NUMBER
AS
  V_TOTAL NUMBER;
BEGIN
  SELECT NVL(SUM(TOTAL), 0) INTO V_TOTAL
  FROM PEDIDOS
  WHERE ESTADO = 'ENTREGADO'
    AND FECHA_PEDIDO >= TRUNC(P_FECHA)
    AND FECHA_PEDIDO <  TRUNC(P_FECHA) + 1;
  RETURN V_TOTAL;
END;
/

