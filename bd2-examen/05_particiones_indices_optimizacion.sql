-- ---------------------------------------------------------------------
-- 5.1 Tabla histórica particionada por RANGO de fechas (por año)
--     en el tablespace histórico
-- ---------------------------------------------------------------------
CREATE TABLE PEDIDOS_HIST (
  ID_PEDIDO    NUMBER(10)   NOT NULL,
  ID_CLIENTE   NUMBER(10)   NOT NULL,
  FECHA_PEDIDO DATE         NOT NULL,
  TIPO_PEDIDO  VARCHAR2(15) NOT NULL,
  METODO_PAGO  VARCHAR2(10) NOT NULL,
  TOTAL        NUMBER(10,2) NOT NULL,
  CONSTRAINT PK_PEDIDOS_HIST PRIMARY KEY (ID_PEDIDO)
    USING INDEX TABLESPACE TBS_POLLERIA_IDX          -- índice GLOBAL (no particionado)
)
TABLESPACE TBS_POLLERIA_HIST
PARTITION BY RANGE (FECHA_PEDIDO) (
  PARTITION P2023    VALUES LESS THAN (DATE '2024-01-01'),
  PARTITION P2024    VALUES LESS THAN (DATE '2025-01-01'),
  PARTITION P2025    VALUES LESS THAN (DATE '2026-01-01'),
  PARTITION P2026    VALUES LESS THAN (DATE '2027-01-01'),
  PARTITION P_FUTURO VALUES LESS THAN (MAXVALUE)
);

-- 5.2 Carga: 5000 pedidos históricos simulados (2023 a mediados de 2027)
