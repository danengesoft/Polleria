-- ---------------------------------------------------------------------
-- 5.6 EXPLAIN PLAN
-- ---------------------------------------------------------------------
-- a) Ventas de 2025 en la tabla particionada:
--    esperado PARTITION RANGE SINGLE con Pstart = 3 y Pstop = 3 (solo P2025)
EXPLAIN PLAN FOR
SELECT *
FROM PEDIDOS_HIST
WHERE FECHA_PEDIDO >= DATE '2025-01-01'
  AND FECHA_PEDIDO <  DATE '2026-01-01';

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

-- b) Sin filtro de fecha: esperado PARTITION RANGE ALL (recorre las 5 particiones)
EXPLAIN PLAN FOR
SELECT TIPO_PEDIDO, SUM(TOTAL)
FROM PEDIDOS_HIST
GROUP BY TIPO_PEDIDO;

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

-- c) De 2024 a 2025: esperado PARTITION RANGE ITERATOR (Pstart = 2, Pstop = 3)
EXPLAIN PLAN FOR
SELECT COUNT(*)
FROM PEDIDOS_HIST
WHERE FECHA_PEDIDO BETWEEN DATE '2024-06-01' AND DATE '2025-06-30';

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

-- d) Un pedido por su clave primaria: INDEX UNIQUE SCAN sobre PK_PEDIDOS_HIST (índice global)
EXPLAIN PLAN FOR
SELECT * FROM PEDIDOS_HIST WHERE ID_PEDIDO = 102500;

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

-- e) Cliente por apellido usando el índice basado en función
EXPLAIN PLAN FOR
SELECT * FROM CLIENTES WHERE UPPER(APELLIDOS) = 'QUISPE MAMANI';

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

-- f) Detalle de un pedido: usa IDX_DETALLE_PEDIDO
--    (con tablas muy pequeñas el CBO puede preferir TABLE ACCESS FULL:
--     eso también es correcto, porque leer toda la tabla le cuesta menos)
EXPLAIN PLAN FOR
SELECT D.*, P.NOMBRE
FROM DETALLE_PEDIDOS D
JOIN PRODUCTOS P ON P.ID_PRODUCTO = D.ID_PRODUCTO
WHERE D.ID_PEDIDO = 10;

SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);
