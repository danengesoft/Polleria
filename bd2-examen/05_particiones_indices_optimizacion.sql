-- 5.3 Consultar particiones
SELECT COUNT(*) AS REGISTROS_2025 FROM PEDIDOS_HIST PARTITION (P2025);

SELECT * FROM PEDIDOS_HIST PARTITION (P2026) WHERE ROWNUM <= 10;

SELECT 'P2023' AS PARTICION, COUNT(*) AS REGISTROS FROM PEDIDOS_HIST PARTITION (P2023)
UNION ALL SELECT 'P2024', COUNT(*) FROM PEDIDOS_HIST PARTITION (P2024)
UNION ALL SELECT 'P2025', COUNT(*) FROM PEDIDOS_HIST PARTITION (P2025)
UNION ALL SELECT 'P2026', COUNT(*) FROM PEDIDOS_HIST PARTITION (P2026)
UNION ALL SELECT 'P_FUTURO', COUNT(*) FROM PEDIDOS_HIST PARTITION (P_FUTURO);

-- ---------------------------------------------------------------------
-- 5.4 ÍNDICES (todos en TBS_POLLERIA_IDX)
-- ---------------------------------------------------------------------
-- Índices B-Tree sobre claves foráneas y columnas de búsqueda
CREATE INDEX IDX_PEDIDOS_CLIENTE     ON PEDIDOS (ID_CLIENTE)          TABLESPACE TBS_POLLERIA_IDX;
CREATE INDEX IDX_PEDIDOS_FECHA       ON PEDIDOS (FECHA_PEDIDO)        TABLESPACE TBS_POLLERIA_IDX;
CREATE INDEX IDX_DETALLE_PEDIDO      ON DETALLE_PEDIDOS (ID_PEDIDO)   TABLESPACE TBS_POLLERIA_IDX;
CREATE INDEX IDX_DETALLE_PRODUCTO    ON DETALLE_PEDIDOS (ID_PRODUCTO) TABLESPACE TBS_POLLERIA_IDX;
CREATE INDEX IDX_PRODUCTOS_CATEGORIA ON PRODUCTOS (ID_CATEGORIA)      TABLESPACE TBS_POLLERIA_IDX;
-- Índice compuesto para "pedidos por estado y fecha"
CREATE INDEX IDX_PEDIDOS_ESTADO_FECHA ON PEDIDOS (ESTADO, FECHA_PEDIDO) TABLESPACE TBS_POLLERIA_IDX;
-- Índice basado en función para buscar clientes por apellido sin importar mayúsculas
CREATE INDEX IDX_CLIENTES_APELLIDOS ON CLIENTES (UPPER(APELLIDOS)) TABLESPACE TBS_POLLERIA_IDX;

-- Índices LOCALES en la tabla particionada (una partición de índice por partición de tabla)
CREATE INDEX IDX_PHIST_FECHA   ON PEDIDOS_HIST (FECHA_PEDIDO) TABLESPACE TBS_POLLERIA_IDX LOCAL;
CREATE INDEX IDX_PHIST_CLIENTE ON PEDIDOS_HIST (ID_CLIENTE)   TABLESPACE TBS_POLLERIA_IDX LOCAL;

-- Mover el índice de la clave primaria de PEDIDOS al tablespace de índices
ALTER INDEX PK_PEDIDOS REBUILD TABLESPACE TBS_POLLERIA_IDX;

