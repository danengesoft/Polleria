       CASE MOD(LEVEL, 4) WHEN 0 THEN 'EFECTIVO' WHEN 1 THEN 'YAPE' WHEN 2 THEN 'PLIN' ELSE 'TARJETA' END,
       ROUND(DBMS_RANDOM.VALUE(15, 150), 2)
FROM DUAL
CONNECT BY LEVEL <= 5000;

