CREATE TABLE CATEGORIAS (
  ID_CATEGORIA NUMBER(10),
  NOMBRE       VARCHAR2(80)  NOT NULL,
  DESCRIPCION  VARCHAR2(300),
  ACTIVO       NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UQ_CATEGORIAS_NOMBRE UNIQUE (NOMBRE),
  CONSTRAINT CK_CATEGORIAS_ACTIVO CHECK (ACTIVO IN (0,1))
) TABLESPACE TBS_POLLERIA_DATOS;

CREATE TABLE PRODUCTOS (
  ID_PRODUCTO  NUMBER(10),
  ID_CATEGORIA NUMBER(10)    NOT NULL,
  NOMBRE       VARCHAR2(120) NOT NULL,
  DESCRIPCION  VARCHAR2(300),
  PRECIO       NUMBER(10,2)  NOT NULL,
  STOCK        NUMBER(10) DEFAULT 0 NOT NULL,
  DISPONIBLE   NUMBER(1)  DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT FK_PRODUCTOS_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS (ID_CATEGORIA),
  CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO > 0),
  CONSTRAINT CK_PRODUCTOS_STOCK CHECK (STOCK >= 0),
  CONSTRAINT CK_PRODUCTOS_DISPONIBLE CHECK (DISPONIBLE IN (0,1))
) TABLESPACE TBS_POLLERIA_DATOS;

CREATE TABLE CLIENTES (
  ID_CLIENTE     NUMBER(10),
  DNI            VARCHAR2(8)   NOT NULL,
  NOMBRES        VARCHAR2(100) NOT NULL,
  APELLIDOS      VARCHAR2(100) NOT NULL,
  TELEFONO       VARCHAR2(12)  NOT NULL,
  CORREO         VARCHAR2(254),
  DIRECCION      VARCHAR2(300),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE),
  CONSTRAINT UQ_CLIENTES_DNI UNIQUE (DNI),
  CONSTRAINT CK_CLIENTES_DNI CHECK (REGEXP_LIKE(DNI, '^[0-9]{8}$')),
  CONSTRAINT CK_CLIENTES_TELEFONO CHECK (REGEXP_LIKE(TELEFONO, '^(\+51)?[0-9]{7,9}$'))
) TABLESPACE TBS_POLLERIA_DATOS;

CREATE TABLE MESAS (
  ID_MESA   NUMBER(10),
  NUMERO    VARCHAR2(10) NOT NULL,
  CAPACIDAD NUMBER(2)    NOT NULL,
  ESTADO    VARCHAR2(15) DEFAULT 'DISPONIBLE' NOT NULL,
  CONSTRAINT PK_MESAS PRIMARY KEY (ID_MESA),
  CONSTRAINT UQ_MESAS_NUMERO UNIQUE (NUMERO),
  CONSTRAINT CK_MESAS_CAPACIDAD CHECK (CAPACIDAD > 0),
  CONSTRAINT CK_MESAS_ESTADO CHECK (ESTADO IN ('DISPONIBLE','RESERVADA','OCUPADA'))
) TABLESPACE TBS_POLLERIA_DATOS;

CREATE TABLE PEDIDOS (
  ID_PEDIDO         NUMBER(10),
  ID_CLIENTE        NUMBER(10)   NOT NULL,
  ID_MESA           NUMBER(10),
  FECHA_PEDIDO      DATE DEFAULT SYSDATE NOT NULL,
  TIPO_PEDIDO       VARCHAR2(15) NOT NULL,
  ESTADO            VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
  METODO_PAGO       VARCHAR2(10) NOT NULL,
  DIRECCION_ENTREGA VARCHAR2(300),
  BASE_IMPONIBLE    NUMBER(10,2) DEFAULT 0 NOT NULL,
  IGV               NUMBER(10,2) DEFAULT 0 NOT NULL,
  TOTAL             NUMBER(10,2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID_PEDIDO),
  CONSTRAINT FK_PEDIDOS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES (ID_CLIENTE),
  CONSTRAINT FK_PEDIDOS_MESA FOREIGN KEY (ID_MESA) REFERENCES MESAS (ID_MESA),
  CONSTRAINT CK_PEDIDOS_TIPO CHECK (TIPO_PEDIDO IN ('MESA','PARA_LLEVAR','DELIVERY')),
  CONSTRAINT CK_PEDIDOS_ESTADO CHECK (ESTADO IN ('PENDIENTE','LISTO','EN_CAMINO','ENTREGADO','CANCELADO')),
  CONSTRAINT CK_PEDIDOS_METODO CHECK (METODO_PAGO IN ('EFECTIVO','YAPE','PLIN','TARJETA')),
  CONSTRAINT CK_PEDIDOS_TOTAL CHECK (TOTAL >= 0 AND TOTAL = BASE_IMPONIBLE + IGV),
  -- Un pedido de MESA debe tener mesa; los demás no.
  CONSTRAINT CK_PEDIDOS_MESA CHECK ((TIPO_PEDIDO = 'MESA' AND ID_MESA IS NOT NULL)
                                 OR (TIPO_PEDIDO <> 'MESA' AND ID_MESA IS NULL)),
  -- Un DELIVERY debe tener dirección.
  CONSTRAINT CK_PEDIDOS_DELIVERY CHECK (TIPO_PEDIDO <> 'DELIVERY' OR DIRECCION_ENTREGA IS NOT NULL),
  -- Solo los DELIVERY pueden estar EN_CAMINO.
  CONSTRAINT CK_PEDIDOS_EN_CAMINO CHECK (ESTADO <> 'EN_CAMINO' OR TIPO_PEDIDO = 'DELIVERY')
) TABLESPACE TBS_POLLERIA_DATOS;

CREATE TABLE DETALLE_PEDIDOS (
  ID_DETALLE      NUMBER(10),
  ID_PEDIDO       NUMBER(10)   NOT NULL,
  ID_PRODUCTO     NUMBER(10)   NOT NULL,
  CANTIDAD        NUMBER(5)    NOT NULL,
  PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
  SUBTOTAL        NUMBER(10,2) NOT NULL,
  CONSTRAINT PK_DETALLE_PEDIDOS PRIMARY KEY (ID_DETALLE),
  CONSTRAINT FK_DETALLE_PEDIDO FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDOS (ID_PEDIDO),
  CONSTRAINT FK_DETALLE_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS (ID_PRODUCTO),
  CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0),
  CONSTRAINT CK_DETALLE_PRECIO CHECK (PRECIO_UNITARIO > 0),
  CONSTRAINT CK_DETALLE_SUBTOTAL CHECK (SUBTOTAL = PRECIO_UNITARIO * CANTIDAD)
) TABLESPACE TBS_POLLERIA_DATOS;

-- Equivalente a la tabla DEPOSITOS de la práctica: registra el cobro de cada pedido.
CREATE TABLE PAGOS (
  ID_PAGO        NUMBER(10),
  ID_PEDIDO      NUMBER(10)   NOT NULL,
  METODO_PAGO    VARCHAR2(10) NOT NULL,
  MONTO          NUMBER(10,2) NOT NULL,
  MONTO_RECIBIDO NUMBER(10,2) NOT NULL,
  VUELTO         NUMBER(10,2) DEFAULT 0 NOT NULL,
  FECHA_PAGO     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_PAGOS PRIMARY KEY (ID_PAGO),
  CONSTRAINT UQ_PAGOS_PEDIDO UNIQUE (ID_PEDIDO),
  CONSTRAINT FK_PAGOS_PEDIDO FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDOS (ID_PEDIDO),
  CONSTRAINT CK_PAGOS_METODO CHECK (METODO_PAGO IN ('EFECTIVO','YAPE','PLIN','TARJETA')),
  CONSTRAINT CK_PAGOS_MONTO CHECK (MONTO > 0 AND MONTO_RECIBIDO >= MONTO AND VUELTO = MONTO_RECIBIDO - MONTO)
) TABLESPACE TBS_POLLERIA_DATOS;

-- La llena automáticamente el trigger TRG_PEDIDOS_CONTROL (script 03).
CREATE TABLE AUDITORIA_PEDIDOS (
  ID_AUDITORIA    NUMBER(10),
  ID_PEDIDO       NUMBER(10)   NOT NULL,
  ACCION          VARCHAR2(20) NOT NULL,
  ESTADO_ANTERIOR VARCHAR2(15),
  ESTADO_NUEVO    VARCHAR2(15),
  USUARIO_BD      VARCHAR2(128) NOT NULL,
  FECHA           DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_AUDITORIA_PEDIDOS PRIMARY KEY (ID_AUDITORIA)
) TABLESPACE TBS_POLLERIA_DATOS;

-- ---------------------------------------------------------------------
-- SECUENCIAS
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_CATEGORIAS START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PRODUCTOS  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CLIENTES   START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_MESAS      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PEDIDOS    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DETALLE    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PAGOS      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_AUDITORIA  START WITH 1 INCREMENT BY 1 NOCACHE;

-- ---------------------------------------------------------------------
-- TRIGGERS QUE ASIGNAN EL ID (BEFORE INSERT + :NEW)
-- ---------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_CATEGORIAS_ID
BEFORE INSERT ON CATEGORIAS FOR EACH ROW
WHEN (NEW.ID_CATEGORIA IS NULL)
BEGIN
  :NEW.ID_CATEGORIA := SEQ_CATEGORIAS.NEXTVAL;
END;
/

