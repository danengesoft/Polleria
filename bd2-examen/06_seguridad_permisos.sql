-- Vista para el analista
CREATE OR REPLACE VIEW V_VENTAS_DIARIAS AS
SELECT TRUNC(FECHA_PEDIDO) AS DIA,
       COUNT(*)            AS PEDIDOS,
       SUM(BASE_IMPONIBLE) AS BASE_IMPONIBLE,
       SUM(IGV)            AS IGV,
       SUM(TOTAL)          AS TOTAL
FROM PEDIDOS
WHERE ESTADO = 'ENTREGADO'
GROUP BY TRUNC(FECHA_PEDIDO);

