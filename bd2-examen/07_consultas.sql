-- 1. Cantidad total de clientes
SELECT COUNT(*) AS TOTAL_CLIENTES FROM CLIENTES;

-- 2. Buscar un cliente por DNI
SELECT * FROM CLIENTES WHERE DNI = '70112233';

-- 3. Productos con su categoría, ordenados por precio
SELECT C.NOMBRE AS CATEGORIA, P.NOMBRE AS PRODUCTO, P.PRECIO, P.STOCK, P.DISPONIBLE
FROM PRODUCTOS P
INNER JOIN CATEGORIAS C ON C.ID_CATEGORIA = P.ID_CATEGORIA
ORDER BY C.NOMBRE, P.PRECIO DESC;

-- 4. Cantidad de pedidos y monto comprado por cliente
SELECT C.NOMBRES || ' ' || C.APELLIDOS AS CLIENTE,
       COUNT(P.ID_PEDIDO) AS PEDIDOS,
       NVL(SUM(P.TOTAL), 0) AS MONTO
FROM CLIENTES C
LEFT JOIN PEDIDOS P ON P.ID_CLIENTE = C.ID_CLIENTE AND P.ESTADO = 'ENTREGADO'
GROUP BY C.NOMBRES, C.APELLIDOS
ORDER BY MONTO DESC;

-- 5. Todos los pedidos de un cliente, con su detalle
SELECT P.ID_PEDIDO, P.FECHA_PEDIDO, P.TIPO_PEDIDO, PR.NOMBRE AS PRODUCTO,
       D.CANTIDAD, D.PRECIO_UNITARIO, D.SUBTOTAL
FROM PEDIDOS P
JOIN DETALLE_PEDIDOS D ON D.ID_PEDIDO = P.ID_PEDIDO
JOIN PRODUCTOS PR      ON PR.ID_PRODUCTO = D.ID_PRODUCTO
WHERE P.ID_CLIENTE = 1
ORDER BY P.FECHA_PEDIDO, D.ID_DETALLE;

-- 6. Ventas por día (base imponible, IGV y total)
SELECT TRUNC(FECHA_PEDIDO) AS DIA, COUNT(*) AS PEDIDOS,
       SUM(BASE_IMPONIBLE) AS BASE, SUM(IGV) AS IGV, SUM(TOTAL) AS TOTAL
FROM PEDIDOS
WHERE ESTADO = 'ENTREGADO'
GROUP BY TRUNC(FECHA_PEDIDO)
ORDER BY DIA;

-- 7. Ventas por tipo de pedido
SELECT TIPO_PEDIDO, COUNT(*) AS PEDIDOS, SUM(TOTAL) AS TOTAL,
       ROUND(AVG(TOTAL), 2) AS TICKET_PROMEDIO
FROM PEDIDOS
WHERE ESTADO = 'ENTREGADO'
GROUP BY TIPO_PEDIDO
ORDER BY TOTAL DESC;

-- 8. Recaudación por método de pago
SELECT METODO_PAGO, COUNT(*) AS PAGOS, SUM(MONTO) AS RECAUDADO, SUM(VUELTO) AS VUELTO_ENTREGADO
FROM PAGOS
GROUP BY METODO_PAGO
ORDER BY RECAUDADO DESC;

-- 9. Ranking de productos más vendidos
SELECT PR.NOMBRE, SUM(D.CANTIDAD) AS UNIDADES, SUM(D.SUBTOTAL) AS IMPORTE
FROM DETALLE_PEDIDOS D
JOIN PRODUCTOS PR ON PR.ID_PRODUCTO = D.ID_PRODUCTO
JOIN PEDIDOS P    ON P.ID_PEDIDO = D.ID_PEDIDO
WHERE P.ESTADO <> 'CANCELADO'
GROUP BY PR.NOMBRE
ORDER BY UNIDADES DESC;

-- 10. Ventas por categoría
SELECT C.NOMBRE AS CATEGORIA, SUM(D.SUBTOTAL) AS IMPORTE
FROM DETALLE_PEDIDOS D
JOIN PRODUCTOS PR  ON PR.ID_PRODUCTO = D.ID_PRODUCTO
JOIN CATEGORIAS C  ON C.ID_CATEGORIA = PR.ID_CATEGORIA
JOIN PEDIDOS P     ON P.ID_PEDIDO = D.ID_PEDIDO
WHERE P.ESTADO = 'ENTREGADO'
GROUP BY C.NOMBRE
ORDER BY IMPORTE DESC;

-- 11. Pedidos pendientes
SELECT P.ID_PEDIDO, OBTENER_NOMBRE_CLIENTE(P.ID_CLIENTE) AS CLIENTE, P.TIPO_PEDIDO,
       P.FECHA_PEDIDO, P.TOTAL
FROM PEDIDOS P
WHERE P.ESTADO = 'PENDIENTE'
ORDER BY P.FECHA_PEDIDO;

-- 12. Estado de las mesas y su pedido abierto
SELECT M.NUMERO, M.CAPACIDAD, M.ESTADO, P.ID_PEDIDO, P.TOTAL
FROM MESAS M
LEFT JOIN PEDIDOS P ON P.ID_MESA = M.ID_MESA AND P.ESTADO NOT IN ('ENTREGADO','CANCELADO')
ORDER BY M.NUMERO;

-- 13. Deliveries con dirección de entrega
SELECT P.ID_PEDIDO, OBTENER_NOMBRE_CLIENTE(P.ID_CLIENTE) AS CLIENTE, C.TELEFONO,
       P.DIRECCION_ENTREGA, P.ESTADO, P.TOTAL
FROM PEDIDOS P
JOIN CLIENTES C ON C.ID_CLIENTE = P.ID_CLIENTE
WHERE P.TIPO_PEDIDO = 'DELIVERY'
ORDER BY P.FECHA_PEDIDO DESC;

-- 14. Productos con stock bajo (menos de 250 unidades)
SELECT NOMBRE, STOCK FROM PRODUCTOS WHERE STOCK < 250 ORDER BY STOCK;

-- 15. Pedidos cancelados y quién los canceló (auditoría)
SELECT A.ID_PEDIDO, A.ESTADO_ANTERIOR, A.ESTADO_NUEVO, A.USUARIO_BD, A.FECHA
FROM AUDITORIA_PEDIDOS A
WHERE A.ESTADO_NUEVO = 'CANCELADO';

-- 16. Clientes que nunca compraron
SELECT C.NOMBRES || ' ' || C.APELLIDOS AS CLIENTE
FROM CLIENTES C
WHERE NOT EXISTS (SELECT 1 FROM PEDIDOS P WHERE P.ID_CLIENTE = C.ID_CLIENTE);

-- 17. Pedidos por encima del ticket promedio (subconsulta)
SELECT ID_PEDIDO, TOTAL
FROM PEDIDOS
WHERE ESTADO = 'ENTREGADO'
  AND TOTAL > (SELECT AVG(TOTAL) FROM PEDIDOS WHERE ESTADO = 'ENTREGADO')
ORDER BY TOTAL DESC;

-- 18. Histórico: ventas por año (tabla particionada)
SELECT EXTRACT(YEAR FROM FECHA_PEDIDO) AS ANIO, COUNT(*) AS PEDIDOS, SUM(TOTAL) AS TOTAL
FROM PEDIDOS_HIST
GROUP BY EXTRACT(YEAR FROM FECHA_PEDIDO)
ORDER BY ANIO;
